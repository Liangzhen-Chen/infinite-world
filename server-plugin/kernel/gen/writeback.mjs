// 写回器（卷十 §4.9 :732；本卡只建自然量与水体两阶段要的最小部分）：生成器交出的行提案经它落成表 `generated` 节的偏离行，没有别的通道（R10-9.2 :745、R10-9.4 :747）。
// 落盘前逐条核对：
//   ① 阶段只能写它 writesKinds 声明过的实体类（R10-9.9 :752）；
//   ② 提案只带表头登记的、无 derived 的维度（由格派生的量不写，R10-9.12 :755；与手写行同一校验）；值过卷二同一个取值校验 checkValue（R10-9.1 :744）；不过即 E-GEN-ROW-INVALID；
//   ③ 作者已有值的维度不覆盖（R10-1.7 :374）：提案的维度作者行上已有值（map 维度按键）即 E-GEN-OVERRIDE-AUTHORED；
//   ④ 同一行被后行阶段补维度时只补没写过的，已生成的不改（R10-1.2 :369）。
// 落成的形状：`generated[id] = {<维度>: <整值>, generated: {by: 产生它的阶段代号, seedKey, at: genesisMinute}}`（卷十 §2.4 :213、R10-9.2；卷二 §1.3 偏离行只写整值）。
// 偏离行与同 id 的作者行逐维合并、偏离行覆盖（卷二 §1.3 覆盖顺序），所以补缺只写作者行没有的维度，作者值留在原行不动；"生成补缺"这一来源就是"在 generated 节里、带 generated 标记"，
// 与作者行里手写的值一眼分得开。以后作者在作者行手写了这一维：下一次世界创建时生成器读到作者值、不再出这一维的提案（R10-1.7），不用改代码。
// `generated.by` 一行只一个：同一行被两个阶段补时记先写的阶段（卷十没给按维度记来源的写法，见回报）。
// 提案里的行不在表里的（作者输入里有、转换前还没进表的行）不落盘，列入 pending 交调用方（它们进表时由转换写，G5b）。

import { KernelError } from '../errors.mjs';
import { checkValue } from '../validate/types.mjs';

const isObj = (v) => v !== null && typeof v === 'object' && !Array.isArray(v);
const cmp = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

/**
 * @param {{
 *   table: string, stage: string, stageEntry: {writesKinds: string[]}, proposals: Array<{table: string, id: string, dims: Record<string, any>, by: string, seedKey: string}>,
 *   rows: Map<string, import('./rows.mjs').GenRow>, tableIds: Set<string>, dims: Record<string, any>, env: any, genesisMinute: number,
 *   generated: Record<string, any>, isAuthored?: (id: string, dim: string) => boolean
 * }} ctx
 *   rows：作者行视图；tableIds：表里真有的行 id；dims：表头；env：加载结果的 env（checkValue 的环境）；generated：已写下的偏离行（先行阶段的，本函数不改它）；
 *   isAuthored：该行该维度的值是作者写的（带 revise 的提案必须交它）；提案带 revise: true 表示改写先行阶段已生成的同一维度（投影），只许改生成值
 * @returns {{generated: Record<string, any>, pending: Array<{id: string, dims: Record<string, any>, by: string, seedKey: string}>}} 合并后的 generated 节（新对象）与不进表的待转换提案
 */
export function writeback(ctx) {
  const out = {};
  for (const [id, row] of Object.entries(ctx.generated)) out[id] = { ...row, generated: { ...row.generated } };
  const pending = [];
  const bad = (code, why) => { throw new KernelError(code, {}, why); };
  if (!ctx.stageEntry.writesKinds.includes(ctx.table)) bad('E-GEN-ROW-INVALID', `stage ${ctx.stage} does not declare writesKinds ${ctx.table} (R10-9.9)`);
  for (const p of ctx.proposals) {
    if (p.table !== ctx.table) bad('E-GEN-ROW-INVALID', `proposal ${p.id}: table ${p.table} is not ${ctx.table}`);
    const author = ctx.rows.get(p.id);
    if (!author) bad('E-GEN-ROW-INVALID', `proposal ${p.id}: no such row in the authored view (a stage fills gaps of existing rows, it does not invent rows here)`);
    for (const [dim, v] of Object.entries(p.dims)) {
      const def = ctx.dims[dim];
      if (!def) bad('E-GEN-ROW-INVALID', `proposal ${p.id}: dimension ${dim} is not registered`);
      if (def.derived !== undefined) bad('E-GEN-ROW-INVALID', `proposal ${p.id}: ${dim} is derived (grid-derived quantities are not generation inputs, R10-9.12)`);
      if (p.revise === true) {
        // 改写先行阶段已生成的同一维度（高低次序投影，R10-2.18）：只许改生成值，作者值一个不动（改作者值即 E-GEN-OVERRIDE-AUTHORED，与"要补的维度作者已有值"同码）。
        // 作者行视图已并上先行阶段的生成值，分不出来源，所以来源由调用方交入的 isAuthored 判。
        if (typeof ctx.isAuthored !== 'function') bad('E-GEN-ROW-INVALID', `proposal ${p.id}: a revising proposal needs ctx.isAuthored (author values must be told from generated ones)`);
        if (ctx.isAuthored(p.id, dim)) bad('E-GEN-OVERRIDE-AUTHORED', `proposal ${p.id}: ${dim} is an authored value, a projection never changes it (R10-2.18, R10-1.7)`);
      } else if (author.dims[dim] !== undefined) {
        const keys = isObj(author.dims[dim]) && isObj(v) ? Object.keys(v).filter((k) => author.dims[dim][k] !== undefined) : [dim];
        if (keys.length > 0) bad('E-GEN-OVERRIDE-AUTHORED', `proposal ${p.id}: ${dim} already has an authored value (${keys.join(',')}), handwritten first (R10-1.7)`);
      }
      const errs = [];
      checkValue(def, v, ctx.env, { table: ctx.table, row: p.id, dim, path: `generated/${p.id}/${dim}` }, (e) => errs.push(e));
      if (errs.length > 0) bad('E-GEN-ROW-INVALID', `proposal ${p.id}: ${dim}=${JSON.stringify(v)} fails the dimension check (${errs[0].code}, want ${errs[0].want})`);
    }
    if (!ctx.tableIds.has(p.id)) { pending.push({ id: p.id, dims: p.dims, by: p.by, seedKey: p.seedKey, ...(p.revise === true ? { revise: true } : {}) }); continue; }
    const had = out[p.id];
    const row = had || { generated: { by: p.by, seedKey: p.seedKey, at: ctx.genesisMinute } };
    for (const [dim, v] of Object.entries(p.dims)) {
      if (p.revise === true) {
        if (row[dim] === undefined) bad('E-GEN-ROW-INVALID', `proposal ${p.id}: ${dim} has no generated value to revise (a projection only moves generated values)`);
      } else if (row[dim] !== undefined) bad('E-GEN-ROW-INVALID', `proposal ${p.id}: ${dim} was already generated by an earlier stage (a later stage only fills what is unwritten, R10-1.2)`);
      row[dim] = v;
    }
    out[p.id] = row;
  }
  const sorted = {};
  for (const id of Object.keys(out).sort(cmp)) sorted[id] = out[id];
  return { generated: sorted, pending };
}

/**
 * 加载期核对（卷十 R10-1.7 :374、E-GEN-OVERRIDE-AUTHORED :239）：同表同 id 的 generated 行与作者行写了同一维度（map 维度按键）即报错，
 * 保证生成值不会静默压过手写值（偏离行覆盖实体行，卷二 §1.3）；作者以后手写了这一维，须同时删去偏离行里的那一维。不按 id、不按表。
 * @param {Map<string, {kind?: string, doc: Record<string, any>}>} tables 加载结果的表 @returns {string[]} 错误行 "<码> <表/行> <说明>"
 */
export function checkGeneratedOverAuthored(tables) {
  const errors = [];
  for (const [kind, t] of tables) {
    const authored = isObj(t.doc.rows) ? t.doc.rows : {};
    const dims = isObj(t.doc.dimensions) ? t.doc.dimensions : {};
    for (const id of Object.keys(isObj(t.doc.generated) ? t.doc.generated : {}).sort(cmp)) {
      if (!Object.hasOwn(authored, id)) continue;
      for (const dim of Object.keys(t.doc.generated[id]).sort(cmp)) {
        if (!Object.hasOwn(dims, dim) || authored[id][dim] === undefined) continue;
        const g = t.doc.generated[id][dim];
        const a = authored[id][dim];
        const clash = isObj(g) && isObj(a) ? Object.keys(g).filter((k) => a[k] !== undefined) : [dim];
        if (clash.length > 0) errors.push(`E-GEN-OVERRIDE-AUTHORED ${kind}/${id} ${dim} is written by both the authored row and the generated row (${clash.join(',')})`);
      }
    }
  }
  return errors;
}

/**
 * 把生成的偏离行并进一张表文档的 `generated` 节（新对象，不改入参）。表里同 id 的偏离行已有时逐维覆盖。
 * @param {Record<string, any>} doc 表文档 @param {Record<string, any>} generated 偏离行
 * @returns {Record<string, any>}
 */
export function applyGenerated(doc, generated) {
  return { ...doc, generated: { ...(isObj(doc.generated) ? doc.generated : {}), ...generated } };
}
