export function highWildlifeFoundation(){
    const locations=regions.map(([slug,name,parent,coordinates,terrain])=>({id:`site_${slug}`,name,aliases:[],parent,coordinates,terrain,
        description:landscape[regions.findIndex(r=>r[0]===slug)]}));
    const habitats=regions.map(([slug,name])=>({id:`habitat_${slug}`,name:`${name}野地`,location:`site_${slug}`}));
    const climates=regions.map(([slug,, , , ,latitude,temperatures])=>({id:`climate_${slug}`,locations:[`site_${slug}`],indoor:[],latitude,temperatures}));
    const monsters=rows.map(([slug,name,h,lo,hi,diet,grouping,distinction,bodyMassKg,material,units,nocturnal])=>{
        const template=regions[h][8],drops=material?[{item:{hide:'item_rawhide',resin:'item_resin',fish:'item_fish'}[material],amount:units}]:[];
        const possible=['草食','肉食','杂食'].includes(diet),food=diet==='草食'?'item_oats':diet==='肉食'?'item_fish':'item_ration';
        return{id:`monster_${slug}`,name,aliases:[],template,levelRange:[lo,hi],habitatTags:[habitats[h].name],grouping,diet,bodyMassKg,drops,
            territoriality:diet==='肉食'?'守护巢区与固定伏猎点，接近时先示警，退离后不持续追逐':diet==='土壤养分'||diet==='腐木'?'依附湿土或腐木，触动根体才防御，不追赶远离者':'以食源与休息处为活动中心，受惊时让路，围堵幼体时防御',
            intelligence:1,taming:{possible,conditions:possible?['需要相称等级与高级驯兽知识','持续建立信任并供应实际合适食物']:['需要相关生态知识和专门研究']},
            ...(possible?{tamingRule:{category:'combat',minimumSkill:Math.min(2699,(template-1)*300),minimumPlayerLevel:lo,trustThreshold:Math.min(95,50+template*5),minutes:120,
                difficulty:template<=4?20:template<=6?25:30,food:[{item:food,hungerRelief:35,trustGain:3}],skills:['辨认口令','跟随训练'],rideable:false,riderWeightKg:60,carryKg:Math.max(1,Math.floor(bodyMassKg/10))}}:{}),
            wildlife:{habitat:habitats[h].id,population:template<=4?6:template<=6?4:2,capacity:template<=4?12:template<=6?8:4,recoveryPerWeek:template<=4?.5:template<=6?.2:.05,
                activeHours:nocturnal?[1080,360]:[360,1080],predatorOf:(feedingLinks[slug]??[]).map(p=>`monster_${p}`),distinction,gather:{minutes:Math.min(120,20+template*10),tool:drops.length?'item_kitchen_knife':null,
                    consumes:drops.length?[{item:'item_water',amount:Math.max(1,Math.ceil(units/3))}]:[]}}};
    });
    // Stable starting food webs do not replenish extinction: births still require two survivors.
    for(const s of monsters){
        if(s.wildlife.predatorOf.length)Object.assign(s.wildlife,{population:2,capacity:3,recoveryPerWeek:.01});
        const consumers=monsters.filter(p=>p.wildlife.predatorOf.includes(s.id)).length;
        if(consumers)Object.assign(s.wildlife,{population:12+4*consumers,capacity:24+8*consumers,recoveryPerWeek:consumers+1});
    }
    return{kind:'highWildlife',monsters,locations,climates,rules:{habitats},routeSpecs:regions.map(([slug,,parent,,,,,closedSeasons])=>({id:`route_${slug}`,from:parent,to:`site_${slug}`,closedSeasons}))};
}
export function withHighWildlife(world,monsters){
    const w=structuredClone(world),bones=highWildlifeFoundation(),merge=(a,b)=>[...new Map([...a,...b].map(x=>[x.id,x])).values()];
    w.locations=merge(w.locations,bones.locations);w.monsters=merge(w.monsters,monsters??bones.monsters);
    w.rules.wildlife.habitats=merge(w.rules.wildlife.habitats,bones.rules.habitats);w.rules.weather.regions=merge(w.rules.weather.regions,bones.climates);
    const points=new Map(w.locations.map(l=>[l.id,l.coordinates]));
    const routes=bones.routeSpecs.map(r=>({...r,lengthKm:Math.round(Math.hypot(points.get(r.from)[0]-points.get(r.to)[0],points.get(r.from)[1]-points.get(r.to)[1])*1.1*100)/100,
        terrainMultiplier:1.5,modes:['walk'],toll:0,risk:0}));
    w.routes=merge(w.routes,routes);return w;
}
