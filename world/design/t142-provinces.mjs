const HIER=(prov,county,id,name)=>[{id:'known-continent',name:'已知大陆片区'},{id:prov.id,name:prov.name},{id:county.id,name:county.name},{id,name}];
const countyById=id=>counties.find(c=>c.id===id),provinceById=id=>provinces.find(p=>p.id===id);
export function buildRegion(row){
 const isCounty=!!row.province,prose=row.prose;
 const description=Object.values(prose).join('\n');
 const references=[...new Set([...(row.places??[]),...(row.seat?.location?[row.seat.location]:[]),...(row.factions??[]),...(row.ruler?.faction?[row.ruler.faction]:[]),
  ...(row.keyPeople??[]).filter(p=>p.person).map(p=>p.person),...(isCounty?[row.province]:row.counties),...(row.ties??row.neighbors??[]).map(t=>t.with)])];
 return{id:row.id,name:row.name,aliases:row.aliases??[],category:isCounty?'county':'province',scope:'global',level:isCounty?'郡':'省',
  ...(isCounty?{province:row.province}:{counties:[...row.counties]}),center:[...row.center],terrain:row.terrain,biomes:biomesOf(row.terrain),climate:row.climate,
  industry:[...row.industry],...(isCounty?{population:row.population,control:row.control,ruler:{...row.ruler},places:[...row.places],factions:[...row.factions],ties:structuredClone(row.ties)}
   :{polity:row.polity,neighbors:structuredClone(row.neighbors)}),
  seat:{...row.seat},keyPeople:structuredClone(row.keyPeople),prose:{...prose},description,references};
}
export function buildNode(n){
 const county=countyById(n.county),prov=provinceById(county.province);
 return{id:n.id,name:n.name,coordinates:[...n.coordinates],parent:null,scope:n.id,aliases:[],terrain:n.terrain,openHours:[0,1440],
  mapHierarchy:HIER(prov,county,n.id,n.name),region:n.county,farNode:n.kind,description:n.description};
}
