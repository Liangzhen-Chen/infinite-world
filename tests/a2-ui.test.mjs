import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {tmpRoot} from '../tools/tmp-root.mjs';
import {chromium} from 'playwright-core';
import {uiSession} from './helpers/ui-script.mjs';
test('390×844 对话面板：点击在场者、寒暄、询问、告辞，无 LLM、无脚本错误',{timeout:60000},async t=>{
 const ui=await uiSession(t,{mutate:s=>{s.npcs.npc_hw_linsui.goals={};}});
 const work=await fs.mkdtemp(path.join(tmpRoot(),'a2-ui-'));
 const browser=await chromium.launchPersistentContext(path.join(work,'profile'),{executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,artifactsDir:work,downloadsPath:work,viewport:{width:390,height:844}});t.after(()=>browser.close());
 const page=await browser.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.exposeFunction('a2Api',(endpoint,body)=>ui.server.api(endpoint,{...body,campaignId:ui.campaignId}));
 await page.exposeFunction('a2Act',async(action,slots)=>({result:await ui.choose(action,slots,{search:true}),document:await ui.read()}));
 await page.route('**/actions-view.mjs',async route=>route.fulfill({contentType:'text/javascript',body:await fs.readFile('extension/actions-view.mjs','utf8')}));
 await page.route('**/actions-view.css',async route=>route.fulfill({contentType:'text/css',body:await fs.readFile('extension/actions-view.css','utf8')}));
 await page.route('**/fixture',route=>route.fulfill({contentType:'text/html',body:'<!doctype html><meta name="viewport" content="width=device-width"><link rel="stylesheet" href="/actions-view.css"><div id="panel"></div>'}));
 await page.goto('http://localhost/fixture');
 await page.evaluate(async document=>{
  const {renderActionsPanel}=await import('/actions-view.mjs');
  const data={view:{document},api:window.a2Api,act:async(action,slots)=>{const out=await window.a2Act(action,slots);data.view={document:out.document};return out.result;}};
  await renderActionsPanel(window.document.querySelector('#panel'),data);
 },await ui.read());
 await page.getByRole('button',{name:/^林穗/}).first().click();
 await page.locator('[aria-label="对话面板"]').waitFor();
 await page.locator('[aria-label="对话面板"]').getByRole('button',{name:'寒暄',exact:true}).click();
 await page.locator('form button[type="submit"]').click();
 await page.locator('.fields-actions-stream').getByText(/林穗/).first().waitFor();
 await page.locator('[aria-label="对话面板"]').getByRole('button',{name:'询问',exact:true}).click();
 await page.locator('#fields-slot-content').fill('陌生的秘密');await page.locator('form button[type="submit"]').click();
 await page.locator('.fields-actions-stream').getByText(/不知道/).first().waitFor();
 await page.locator('[aria-label="对话面板"]').getByRole('button',{name:'告辞',exact:true}).click();await page.locator('form button[type="submit"]').click();
 await page.locator('.fields-actions-stream').getByText(/回头见/).first().waitFor();
 assert.deepEqual(errors,[]);assert.equal((await ui.read()).state.dialogues.npc_hw_linsui.action,'leave');
});
