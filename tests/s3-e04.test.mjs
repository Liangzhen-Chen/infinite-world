import test from 'node:test';
import assert from 'node:assert/strict';
import {materialScenario,stolenScenario} from './probes/run-001/e04-scenarios.mjs';
import {fixture,host,worker,clerk} from './helpers/finance.mjs';
import {openLedger} from '../server-plugin/ledger.mjs';
import {reconcile} from './helpers/ledger-audit.mjs';
import {scheduleAt} from '../server-plugin/npc-schedule.mjs';
import {applyPatches} from '../server-plugin/storage.mjs';
test('E04-2: actual extraction, strike, stock-driven prices, purchases and crafting',materialScenario);
test('E04-3: upper court, stolen provenance, receiving case and witnessed report',stolenScenario);
test('E04-3: recovered ore can be purchased and resold without reviving the old offense',async()=>{
 const f=fixture(),item='item_iron_ore',unit='unit_e04_recovered';
 f.doc.state.npcs[host].inventory[item]={quantity:1,instances:[unit]};
 f.doc.state.itemInstances??={};
 f.doc.state.itemInstances[unit]={id:unit,item,owner:host,status:'持有',stolenOrigin:{event:'old-dig',victim:clerk,recoveredAt:0,recoveryEvent:'old-claim'}};
 f.doc.ledger=openLedger(f.e,f.doc);
 const bought=await f.act({seller:host,item,quantity:1,instances:[unit]},'e04-recovered-purchase');
 assert.equal(bought.receivingCases,undefined);
 const resold=await f.act({seller:'player',buyer:worker,item,quantity:1,instances:[unit]},'e04-recovered-resale');
 assert.equal(resold.receivingCases,undefined);assert.equal(f.doc.state.itemInstances[unit].owner,worker);
 assert.deepEqual(reconcile(f.e,f.doc),{mismatches:[],lots:[],drift:[],audit:[]});
});
test('E04-2: smelting can be learned through the authored smith and teaching hours',async()=>{
 const f=fixture(),smith='npc_hw_duanyan',recipe='recipe_smelt_iron';
 f.doc.state.minute=840;
 const slot=scheduleAt(f.e,smith,840,f.doc.state);assert.ok(slot.services.includes('teach'));
 f.doc.state.location=slot.location;
 f.doc.state.npcs[smith]={status:'正常',activity:'在炉边指点',location:slot.location,coins:200,inventory:{}};
 f.doc.state.skills.skill_life_5_core={proficiency:0,daily:{}};
 f.doc.state.player.attributes={...f.doc.state.player.attributes,智力:100};
 f.doc.ledger=openLedger(f.e,f.doc);
 const out=await f.e.reduce(f.doc,{tool:'world_learn',args:{kind:'recipe',entity:recipe,source:smith},eventId:'e04-learn-smelting'});
 f.doc=applyPatches(f.doc,out.patches);
 assert.equal(out.result.success,true);assert.ok(f.doc.state.recipes[recipe]);
 assert.deepEqual(reconcile(f.e,f.doc),{mismatches:[],lots:[],drift:[],audit:[]});
});
