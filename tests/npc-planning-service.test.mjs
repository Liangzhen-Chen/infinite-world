import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import {once}from'node:events';
import express from 'express';
import {init}from'../server-plugin/index.mjs';
import {npcPlanFingerprint}from'../server-plugin/npc-autonomy.mjs';

test('智能规划在动作后冻结入账；同日、重复请求和导入回放不再调用模型，撤销同锚点一起回滚',async t=>{
    const root=await fs.mkdtemp(path.join(os.tmpdir(),'fields-npc-plan-'));t.after(()=>fs.rm(root,{recursive:true,force:true}));
    let calls=0;
    const planner=async(engine,document)=>{calls++;return{status:'ready',input:{type:'npc_plan',plan:{kind:'npc-plan',version:1,minute:document.state.minute,stateFingerprint:npcPlanFingerprint(document),proposals:[]}}};};
    const app=express();app.use(express.json({limit:'50mb'}));const router=express.Router();await init(router,{baseRoot:root,npcPlanner:planner,npcPlanningEnabled:true});app.use(router);
    const server=app.listen(0,'127.0.0.1');await once(server,'listening');t.after(()=>server.close());
    const api=async(endpoint,body)=>{const r=await fetch(`http://127.0.0.1:${server.address().port}/${endpoint}`,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});const data=await r.json();assert.equal(r.status,200,data.error);return data;};
    const initial=await api('create',{name:'规划测试'}),campaignId=initial.reference.campaignId;
    const moved=await api('execute',{campaignId,tool:'world_move',args:{destination:'loc_hw'},eventId:'leave',anchor:'move-anchor'});
    assert.equal(calls,1);assert.equal(moved.npcPlanning.status,'applied');assert.equal(moved.document.state.npcPlanning.day,0);
    await api('execute',{campaignId,tool:'world_move',args:{destination:'loc_hw'},eventId:'leave',anchor:'move-anchor'});assert.equal(calls,1);
    const exported=await api('export',{campaignId});assert.equal(exported.events.filter(e=>e.input.type==='npc_plan').length,1);
    const imported=await api('import',{bundle:exported});assert.deepEqual(imported.document,moved.document);assert.equal(calls,1);
    const rewound=await api('reconcile',{campaignId,validAnchors:[],excludeAnchor:'move-anchor'});
    assert.equal(rewound.document.state.npcPlanning,undefined);assert.equal(rewound.document.state.location,initial.document.state.location);assert.equal(calls,1);
    const renewed=await api('execute',{campaignId,tool:'world_move',args:{destination:'loc_hw'},eventId:'leave-again',anchor:'new-anchor'});
    assert.equal(renewed.npcPlanning.status,'applied');assert.equal(renewed.document.state.npcPlanning.day,0);
    assert.notEqual(renewed.npcPlanning.eventId,moved.npcPlanning.eventId);
    const renewedExport=await api('export',{campaignId});assert.equal(renewedExport.events.filter(e=>e.input?.type==='npc_plan').length,2);
});
