import { chromium } from 'playwright-core';
import fs from 'node:fs/promises';
import path from 'node:path';
const logsDirectory=path.resolve(import.meta.dirname,'../logs');
await fs.mkdir(logsDirectory,{recursive:true});
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const context=await browser.newContext({locale:'zh-CN'});
const page=await context.newPage();
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.addInitScript(()=>localStorage.setItem('language','zh-cn'));
await page.goto('http://127.0.0.1:8000/',{waitUntil:'domcontentloaded',timeout:60000});
await page.waitForFunction(()=>window.infiniteFields && document.querySelector('#fields-toolbar'),{timeout:60000});
await page.waitForFunction(()=>SillyTavern.getContext().onlineStatus !== 'no_connection',{},{timeout:60000});
const result=await page.evaluate(async()=>{
    const c=SillyTavern.getContext();
    const {oai_settings}=await import('/scripts/openai.js');
    return {name:c.name2,chatId:c.chatId,api:c.mainApi,status:c.onlineStatus,source:oai_settings.chat_completion_source,model:oai_settings.deepseek_model,toolCalling:oai_settings.function_calling,toolsSupported:c.isToolCallingSupported(),memoryCount:Object.keys(window.infiniteFields.campaign().memories).length,state:c.chatMetadata.infinite_fields.state.player,tools:c.ToolManager.tools.map(v=>v.toFunctionOpenAI().function.name),chatLength:c.chat.length,toolbar:document.querySelector('#fields-status')?.textContent};
});
await page.locator('#fields-toolbar button').click();
await page.locator('#fields-dialog').waitFor({state:'visible'});
await page.screenshot({path:path.join(logsDirectory,'账本检查.png'),fullPage:false});
console.log(JSON.stringify({result,errors}));
await browser.close();
